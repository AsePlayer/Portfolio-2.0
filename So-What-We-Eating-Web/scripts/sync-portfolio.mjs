import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--portfolio')) {
  throw new Error('Usage: node scripts/sync-portfolio.mjs [--portfolio "path/to/Portfolio 2.0"]');
}
const portfolioRoot = fs.realpathSync(args[1] || path.join(appRoot, '..'));
const output = path.join(appRoot, 'dist');
const project = path.join(portfolioRoot, 'projects', 'what-we-eating');
const marker = '.generated-project.json';
const identity = 'so-what-we-eating-web';
const content = JSON.parse(fs.readFileSync(path.join(portfolioRoot, 'data', 'site.json'), 'utf8'));
if (!fs.existsSync(path.join(portfolioRoot, 'scripts', 'build.mjs')) ||
    !content.projects?.items?.some(item => item.id === 'what-we-eating' && item.href === '/projects/what-we-eating/')) {
  throw new Error('Configure the what-we-eating project card in the selected portfolio first.');
}
if (!fs.existsSync(path.join(output, 'index.html')) || !fs.existsSync(path.join(output, 'sw.js'))) {
  throw new Error('Build the app before syncing: npm run build');
}

function checkDirectory(directory) {
  const relative = path.relative(portfolioRoot, path.resolve(directory));
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Destination must stay inside the portfolio.');
  let current = portfolioRoot;
  for (const segment of relative.split(path.sep)) {
    current = path.join(current, segment);
    if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) throw new Error(`Refusing linked directory: ${current}`);
  }
}

function checkOwnedProject() {
  checkDirectory(project);
  if (fs.existsSync(project)) {
    const ownership = path.join(project, marker);
    if (!fs.existsSync(ownership) || JSON.parse(fs.readFileSync(ownership, 'utf8')).source !== identity) {
      throw new Error('Refusing to replace an app directory not generated by this command.');
    }
  }
}

checkOwnedProject();
const staging = path.join(portfolioRoot, '.tmp', `what-we-eating-${process.pid}`);
checkDirectory(staging);
if (fs.existsSync(staging)) throw new Error('Staging directory already exists; refusing to replace it.');
fs.mkdirSync(staging, {recursive: true});
fs.cpSync(output, staging, {recursive: true, dereference: false});

const htmlPath = path.join(staging, 'index.html');
const html = fs.readFileSync(htmlPath, 'utf8');
const anchor = '<header class="site-header">';
if (!html.includes(anchor)) throw new Error('App header changed; review portfolio return-link insertion.');
const integratedHtml = html.replace(anchor,
  `<a class="portfolio-return" href="../../#projects">&larr; Portfolio</a>\n  ${anchor}`);
fs.writeFileSync(htmlPath, integratedHtml);

// The built worker already hashes every shell file. Include the modified HTML so
// switching between standalone and portfolio builds cannot retain a stale shell.
const workerPath = path.join(staging, 'sw.js');
const worker = fs.readFileSync(workerPath, 'utf8');
if (!/const VERSION='[a-f0-9]+'/.test(worker)) throw new Error('Worker version format changed; review shell generation.');
const version = createHash('sha256').update(worker).update(integratedHtml).digest('hex').slice(0, 16);
fs.writeFileSync(workerPath, worker.replace(/const VERSION='[a-f0-9]+'/, `const VERSION='${version}'`));
fs.writeFileSync(path.join(staging, marker), JSON.stringify({source: identity}, null, 2) + '\n');

// Recheck the exact resolved destination and ownership immediately before replacement.
checkOwnedProject();
fs.mkdirSync(path.dirname(project), {recursive: true});
if (fs.existsSync(project)) fs.rmSync(project, {recursive: true, force: true});
fs.renameSync(staging, project);
console.log(`Synced generated app to ${project}`);
